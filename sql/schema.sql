-- PostgreSQL schema for the Art Gallery Management System
-- Run order (typical): schema.sql -> indexes.sql -> seed.sql -> views/procs/triggers

DROP TABLE IF EXISTS ArtworkSaleLog CASCADE;
DROP TABLE IF EXISTS TicketPurchaseLog CASCADE;
DROP TABLE IF EXISTS Sale CASCADE;
DROP TABLE IF EXISTS Ticket CASCADE;
DROP TABLE IF EXISTS Artwork_Exhibition CASCADE;
DROP TABLE IF EXISTS Artwork CASCADE;
DROP TABLE IF EXISTS Exhibition CASCADE;
DROP TABLE IF EXISTS Visitor CASCADE;
DROP TABLE IF EXISTS Staff CASCADE;
DROP TABLE IF EXISTS Artist CASCADE;
DROP TABLE IF EXISTS Category CASCADE;
DROP TABLE IF EXISTS Curator CASCADE;
DROP TABLE IF EXISTS AdminUser CASCADE;

DROP TYPE IF EXISTS membership_type_enum;

-- Enum to satisfy: membership_type in Visitor: ENUM('Regular','Premium','Student')
CREATE TYPE membership_type_enum AS ENUM ('Regular', 'Premium', 'Student');

-- Artist
CREATE TABLE Artist (
  artist_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  nationality VARCHAR(100) NOT NULL,
  birth_year INTEGER NOT NULL,
  bio TEXT NOT NULL,
  CONSTRAINT artist_name_unique UNIQUE (name)
);

-- Category
CREATE TABLE Category (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  CONSTRAINT category_name_unique UNIQUE (name)
);

-- Artwork (+ CHECK: Artwork price must be > 0)
CREATE TABLE Artwork (
  artwork_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  year_created INTEGER NOT NULL,
  medium VARCHAR(150) NOT NULL,
  price NUMERIC(12,2) NOT NULL,
  sold_count INTEGER NOT NULL DEFAULT 0,
  artist_id INTEGER NOT NULL,
  category_id INTEGER NOT NULL,
  CONSTRAINT artwork_price_positive CHECK (price > 0),
  CONSTRAINT artwork_year_valid CHECK (year_created > 0),
  CONSTRAINT artwork_artist_fk FOREIGN KEY (artist_id)
    REFERENCES Artist (artist_id) ON DELETE CASCADE,
  CONSTRAINT artwork_category_fk FOREIGN KEY (category_id)
    REFERENCES Category (category_id) ON DELETE CASCADE
);

-- Curator
CREATE TABLE Curator (
  curator_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  email VARCHAR(200) NOT NULL,
  phone VARCHAR(50) NOT NULL,
  CONSTRAINT curator_email_unique UNIQUE (email)
);

-- Exhibition
-- Extra column: ticket_price (needed so BookTicket can create a priced Ticket deterministically)
CREATE TABLE Exhibition (
  exhibition_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  theme VARCHAR(200) NOT NULL,
  curator_id INTEGER NOT NULL,
  ticket_price NUMERIC(12,2) NOT NULL DEFAULT 50.00,
  CONSTRAINT exhibition_date_valid CHECK (end_date >= start_date),
  CONSTRAINT exhibition_ticket_price_positive CHECK (ticket_price > 0),
  CONSTRAINT exhibition_curator_fk FOREIGN KEY (curator_id)
    REFERENCES Curator (curator_id) ON DELETE CASCADE
);

-- Junction: many-to-many between Artwork and Exhibition
CREATE TABLE Artwork_Exhibition (
  artwork_id INTEGER NOT NULL,
  exhibition_id INTEGER NOT NULL,
  PRIMARY KEY (artwork_id, exhibition_id),
  CONSTRAINT artwork_exhibition_artwork_fk FOREIGN KEY (artwork_id)
    REFERENCES Artwork (artwork_id) ON DELETE CASCADE,
  CONSTRAINT artwork_exhibition_exhibition_fk FOREIGN KEY (exhibition_id)
    REFERENCES Exhibition (exhibition_id) ON DELETE CASCADE
);

-- Visitor
CREATE TABLE Visitor (
  visitor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  email VARCHAR(200) NOT NULL,
  phone VARCHAR(50) NOT NULL,
  membership_type membership_type_enum NOT NULL,
  CONSTRAINT visitor_email_unique UNIQUE (email)
);

-- Ticket
CREATE TABLE Ticket (
  ticket_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visitor_id INTEGER NOT NULL,
  exhibition_id INTEGER NOT NULL,
  purchase_date DATE NOT NULL,
  price NUMERIC(12,2) NOT NULL,
  seat_type VARCHAR(50) NOT NULL,
  CONSTRAINT ticket_price_positive CHECK (price > 0),
  CONSTRAINT ticket_visitor_fk FOREIGN KEY (visitor_id)
    REFERENCES Visitor (visitor_id) ON DELETE CASCADE,
  CONSTRAINT ticket_exhibition_fk FOREIGN KEY (exhibition_id)
    REFERENCES Exhibition (exhibition_id) ON DELETE CASCADE
);

-- Sale
CREATE TABLE Sale (
  sale_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artwork_id INTEGER NOT NULL,
  visitor_id INTEGER NOT NULL,
  sale_date DATE NOT NULL,
  amount_paid NUMERIC(12,2) NOT NULL,
  CONSTRAINT sale_amount_positive CHECK (amount_paid > 0),
  CONSTRAINT sale_artwork_fk FOREIGN KEY (artwork_id)
    REFERENCES Artwork (artwork_id) ON DELETE CASCADE,
  CONSTRAINT sale_visitor_fk FOREIGN KEY (visitor_id)
    REFERENCES Visitor (visitor_id) ON DELETE CASCADE
);

-- Staff
CREATE TABLE Staff (
  staff_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  role VARCHAR(100) NOT NULL,
  email VARCHAR(200) NOT NULL,
  salary NUMERIC(12,2) NOT NULL,
  CONSTRAINT staff_email_unique UNIQUE (email),
  CONSTRAINT staff_salary_nonnegative CHECK (salary >= 0)
);

-- Admin users for JWT auth (extra table)
CREATE TABLE AdminUser (
  admin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL,
  password_hash TEXT NOT NULL,
  role VARCHAR(50) NOT NULL DEFAULT 'admin',
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT admin_username_unique UNIQUE (username)
);

-- Log tables for triggers (extras)
CREATE TABLE TicketPurchaseLog (
  log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id INTEGER NOT NULL,
  visitor_id INTEGER NOT NULL,
  exhibition_id INTEGER NOT NULL,
  purchase_date DATE NOT NULL,
  price NUMERIC(12,2) NOT NULL,
  seat_type VARCHAR(50) NOT NULL,
  logged_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT ticket_purchase_log_ticket_fk FOREIGN KEY (ticket_id)
    REFERENCES Ticket (ticket_id) ON DELETE CASCADE
);

CREATE TABLE ArtworkSaleLog (
  log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id INTEGER NOT NULL,
  artwork_id INTEGER NOT NULL,
  visitor_id INTEGER NOT NULL,
  sale_date DATE NOT NULL,
  amount_paid NUMERIC(12,2) NOT NULL,
  logged_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT artwork_sale_log_sale_fk FOREIGN KEY (sale_id)
    REFERENCES Sale (sale_id) ON DELETE CASCADE
);

